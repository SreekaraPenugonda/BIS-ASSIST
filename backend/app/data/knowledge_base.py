def normalize_multilingual_query(query: str) -> str:
    normalized = (query or "").lower()
    for source, target in sorted(MULTILINGUAL_QUERY_TERMS.items(), key=lambda item: len(item[0]), reverse=True):
        normalized = normalized.replace(source, f" {target} ")
    return normalized

